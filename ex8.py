# Вводим номер месяца
numOfYear = int(input("Введите номер месяца: "))

# Определяем сезон по номеру месяца
match numOfYear:
    case 1 | 2 | 12:
        print("Ваш сезон - зима")
    case 3 | 4 | 5:
        print("Ваш сезон - весна")
    case 6 | 7 | 8:
        print("Ваш сезон - лето")
    case 9 | 10 | 11:
        print("Ваш сезон - осень")
    case _:
        print("Такого номера несуществует")